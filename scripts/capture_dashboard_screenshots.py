#!/usr/bin/env python3
"""
Capture one PNG per Metabase dashboard into docs/screenshots/.

Why a script: the dashboards are generated by
`scripts/build_metabase_dashboards.py`, so their ids and titles change
whenever that script is re-run. Screenshotting by hand goes stale silently.

How it works
------------
1. Log in through the Metabase API to get a session id.
2. Ask the API for every dashboard in the target collection, so the file
   names always match the current titles.
3. Open each dashboard in headless Chromium with the session cookie already
   set, wait for the cards to finish loading, then take a full-page shot.

Usage
-----
    make screenshots

Requires: playwright (pip) + `playwright install chromium`.
"""

from __future__ import annotations

import argparse
import json
import os
import re
import sys
import urllib.error
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT_DIR = ROOT / "docs" / "screenshots"


# ---------------------------------------------------------------------------
# Minimal Metabase API client (same shape as the dashboard builder)
# ---------------------------------------------------------------------------


class Metabase:
    def __init__(self, base_url: str, user: str, password: str) -> None:
        self.base = base_url.rstrip("/")
        self.session_id: str | None = None
        self._login(user, password)

    def _request(self, method: str, path: str, payload: dict | None = None):
        url = f"{self.base}/api{path}"
        data = json.dumps(payload).encode() if payload is not None else None
        req = urllib.request.Request(url, data=data, method=method)
        req.add_header("Content-Type", "application/json")
        if self.session_id:
            req.add_header("X-Metabase-Session", self.session_id)
        try:
            with urllib.request.urlopen(req, timeout=120) as resp:
                body = resp.read().decode()
                return json.loads(body) if body else None
        except urllib.error.HTTPError as exc:
            raise RuntimeError(
                f"{method} {path} -> HTTP {exc.code}\n{exc.read().decode()[:400]}"
            ) from exc

    def get(self, path: str):
        return self._request("GET", path)

    def post(self, path: str, payload: dict):
        return self._request("POST", path, payload)

    def _login(self, user: str, password: str) -> None:
        result = self.post("/session", {"username": user, "password": password})
        self.session_id = result["id"]
        print(f"[auth] logged in as {user}")

    def find_collection(self, name: str) -> int | None:
        for c in self.get("/collection") or []:
            if c.get("name", "").lower() == name.lower():
                return int(c["id"])
        return None

    def dashboards_in(self, collection_id: int) -> list[dict]:
        items = self.get("/dashboard")
        items = items["data"] if isinstance(items, dict) else items
        return [d for d in items or [] if d.get("collection_id") == collection_id]


# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------


def slugify(name: str) -> str:
    """'1 · Overview — Churn Story' -> 'dashboard_1'."""
    m = re.match(r"\s*(\d+)", name)
    if m:
        return f"dashboard_{m.group(1)}"
    slug = re.sub(r"[^a-z0-9]+", "_", name.lower()).strip("_")
    return f"dashboard_{slug}"


def stitch(slices: list[bytes], out_path: Path) -> None:
    """
    Vertically concatenate viewport screenshots into one tall image.

    Consecutive slices overlap by a few pixels because the page is scrolled by
    exactly one viewport height; the overlap is trimmed so the result has no
    duplicated rows.
    """
    import io

    from PIL import Image

    images = [Image.open(io.BytesIO(b)) for b in slices]
    width = images[0].width
    total_h = sum(im.height for im in images)

    canvas = Image.new("RGB", (width, total_h), "white")
    y = 0
    for im in images:
        canvas.paste(im, (0, y))
        y += im.height

    canvas.save(out_path, optimize=True)


def main() -> int:
    try:
        from dotenv import load_dotenv

        load_dotenv(ROOT / ".env")
    except ImportError:
        pass

    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--url", default=os.getenv("MB_URL", "http://localhost:3000"))
    parser.add_argument("--user", default=os.getenv("MB_USER"))
    parser.add_argument("--password", default=os.getenv("MB_PASS"))
    parser.add_argument("--collection", default=os.getenv("MB_COLLECTION", "Telco Churn DSS"))
    parser.add_argument("--width", type=int, default=1600)
    parser.add_argument("--height", type=int, default=1200)
    parser.add_argument("--wait-ms", type=int, default=9000,
                        help="How long to wait for cards to render.")
    args = parser.parse_args()

    if not args.user or not args.password:
        print(
            "ERROR: Metabase credentials required.\n"
            "Add MB_USER / MB_PASS to .env, then re-run `make screenshots`.",
            file=sys.stderr,
        )
        return 2

    mb = Metabase(args.url, args.user, args.password)
    collection_id = mb.find_collection(args.collection)
    if collection_id is None:
        print(f"ERROR: collection '{args.collection}' not found", file=sys.stderr)
        return 1

    dashboards = sorted(mb.dashboards_in(collection_id), key=lambda d: d["name"])
    if not dashboards:
        print("ERROR: no dashboards in that collection", file=sys.stderr)
        return 1

    print(f"[dashboards] {len(dashboards)} found in '{args.collection}'")
    for d in dashboards:
        print(f"  {d['id']:>3}  {d['name']}")

    OUT_DIR.mkdir(parents=True, exist_ok=True)

    from playwright.sync_api import sync_playwright

    written: list[Path] = []
    with sync_playwright() as pw:
        browser = pw.chromium.launch()
        context = browser.new_context(
            viewport={"width": args.width, "height": args.height},
            device_scale_factor=2,  # retina-quality PNGs
        )
        # Authenticate by setting the session cookie Metabase expects.
        context.add_cookies(
            [
                {
                    "name": "metabase.SESSION",
                    "value": mb.session_id,
                    "domain": "localhost",
                    "path": "/",
                }
            ]
        )
        page = context.new_page()

        for d in dashboards:
            url = f"{args.url}/dashboard/{d['id']}"
            print(f"\n[shot] {d['name']}")
            page.goto(url, wait_until="networkidle", timeout=90_000)
            page.wait_for_timeout(args.wait_ms)

            # Neither `full_page=True` nor a very tall viewport works here:
            # both make Metabase re-mount its cards, and the shot ends up full
            # of loading skeletons. Instead, scroll through the dashboard one
            # viewport at a time, screenshot each position, and stitch the
            # slices together. Every card is therefore rendered while it is
            # actually on screen.
            #
            # Metabase scrolls an inner container, not <body>, so the height
            # has to be read from the scrollable element rather than from
            # document.body.scrollHeight.
            total_h = page.evaluate(
                """() => {
                    const el = document.scrollingElement || document.documentElement;
                    const inner = document.querySelector('[data-testid="dashboard"]')
                               || document.querySelector('main');
                    const h = Math.max(
                        el ? el.scrollHeight : 0,
                        inner ? inner.scrollHeight : 0,
                        document.body.scrollHeight
                    );
                    return h;
                }"""
            )
            print(f"  [info] content height {total_h}px")
            slices: list[bytes] = []
            y = 0
            while True:
                page.evaluate(f"() => window.scrollTo(0, {y})")
                page.wait_for_timeout(2500)
                slices.append(page.screenshot())
                if y + args.height >= total_h:
                    break
                y += args.height

            path = OUT_DIR / f"{slugify(d['name'])}.png"
            stitch(slices, path)
            size_kb = path.stat().st_size / 1024
            print(f"  -> {path.relative_to(ROOT)} ({size_kb:.0f} KB, {len(slices)} slices)")
            written.append(path)

        browser.close()

    print(f"\n[done] {len(written)} screenshots in {OUT_DIR.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
