-- ===========================================================================
--  02_silver_to_gold.sql   (ELT — Kimball star schema, all in SQL)
--
--  Grain of gold.fact_billing_support:
--      1 row = 1 billing cycle of 1 customer
--      business key = (customer_id, billing_cycle_start)
--
--  Design decisions (see PHASES.md decision log):
--    D4  every dimension has a key = 0 'Unknown' member, so the fact never
--        carries a NULL foreign key.
--    D8  rows with no support interaction are NOT unknown — they are a real
--        business state. They map to dim_issue_type 'No Support' and
--        dim_support_channel 'None' (real surrogate keys, is_unknown = FALSE).
--    D9  that mapping happens HERE, in Gold. Silver keeps the source NULLs.
--    D10 dim_date range is computed from the data, never hardcoded, so an
--        incremental batch containing new dates extends the calendar.
--    D11 the key = 0 date row has full_date = NULL (not a 1900-01-01
--        sentinel, which would silently corrupt `WHERE full_date <= X`).
-- ===========================================================================

BEGIN;

-- ---------------------------------------------------------------------------
-- 1. dim_date
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS gold.dim_date (
    date_key    INTEGER   PRIMARY KEY,          -- YYYYMMDD, 0 = unknown
    full_date   DATE,
    day         INTEGER,
    month       INTEGER,
    quarter     INTEGER,
    year        INTEGER,
    weekday     INTEGER,                        -- ISO: 1 = Monday .. 7 = Sunday
    is_weekend  BOOLEAN,
    is_unknown  BOOLEAN   NOT NULL DEFAULT FALSE,

    CONSTRAINT ck_dim_date_unknown CHECK (date_key = 0 OR full_date IS NOT NULL)
);

COMMENT ON TABLE gold.dim_date IS
  'Date dimension. Hierarchy: year -> quarter -> month -> day (indexed for OLAP roll-up/drill-down).';
COMMENT ON COLUMN gold.dim_date.date_key IS
  'Surrogate key YYYYMMDD. 0 = Unknown (full_date IS NULL).';

-- Hierarchy index: makes ROLLUP(year, quarter, month) and drill-down cheap.
CREATE INDEX IF NOT EXISTS ix_dim_date_hierarchy
    ON gold.dim_date (year, quarter, month, day);

-- Natural key, needed for the LEFT JOIN from silver and for uniqueness.
CREATE UNIQUE INDEX IF NOT EXISTS ux_dim_date_full_date
    ON gold.dim_date (full_date);

-- Unknown member (must exist before the fact load)
INSERT INTO gold.dim_date
    (date_key, full_date, day, month, quarter, year, weekday, is_weekend, is_unknown)
VALUES
    (0, NULL, NULL, NULL, NULL, NULL, NULL, NULL, TRUE)
ON CONFLICT (date_key) DO NOTHING;

-- Calendar generated from the ACTUAL data range across all four date columns.
-- `min_d + n` uses the date + integer operator: no timestamp/timestamptz
-- intermediate, therefore no dependency on the session TimeZone.
WITH date_range AS (
    SELECT MIN(d)::date AS min_d, MAX(d)::date AS max_d
    FROM (
        SELECT billing_cycle_start     AS d FROM silver.silver_customer_billing
        UNION ALL
        SELECT billing_cycle_end       AS d FROM silver.silver_customer_billing
        UNION ALL
        SELECT payment_due_date        AS d FROM silver.silver_customer_billing
        UNION ALL
        SELECT last_interaction_date   AS d FROM silver.silver_customer_billing
    ) t
    WHERE d IS NOT NULL
)
INSERT INTO gold.dim_date
    (date_key, full_date, day, month, quarter, year, weekday, is_weekend, is_unknown)
SELECT
    TO_CHAR(r.min_d + g.n, 'YYYYMMDD')::int,
    (r.min_d + g.n)::date,
    EXTRACT(DAY     FROM (r.min_d + g.n))::int,
    EXTRACT(MONTH   FROM (r.min_d + g.n))::int,
    EXTRACT(QUARTER FROM (r.min_d + g.n))::int,
    EXTRACT(YEAR    FROM (r.min_d + g.n))::int,
    EXTRACT(ISODOW  FROM (r.min_d + g.n))::int,
    EXTRACT(ISODOW  FROM (r.min_d + g.n)) IN (6, 7),
    FALSE
FROM date_range r
CROSS JOIN LATERAL generate_series(0, (r.max_d - r.min_d)) AS g(n)
ON CONFLICT (date_key) DO NOTHING;

-- ---------------------------------------------------------------------------
-- 2. dim_customer
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS gold.dim_customer (
    customer_key  INTEGER   GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id   TEXT      NOT NULL,
    is_unknown    BOOLEAN   NOT NULL DEFAULT FALSE,

    -- SCD2 scaffolding, documented but not activated (see README "Extensions")
    valid_from    TIMESTAMP NOT NULL DEFAULT NOW(),
    valid_to      TIMESTAMP,
    is_current    BOOLEAN   NOT NULL DEFAULT TRUE,

    CONSTRAINT uq_dim_customer_natural UNIQUE (customer_id)
);

COMMENT ON TABLE gold.dim_customer IS
  'Customer dimension. SCD2 columns present for documentation; current load is Type 1.';

INSERT INTO gold.dim_customer (customer_key, customer_id, is_unknown)
VALUES (0, 'Unknown', TRUE)
ON CONFLICT (customer_key) DO NOTHING;

INSERT INTO gold.dim_customer (customer_id)
SELECT DISTINCT s.customer_id
FROM silver.silver_customer_billing s
WHERE s.customer_id IS NOT NULL
ON CONFLICT (customer_id) DO NOTHING;

-- ---------------------------------------------------------------------------
-- 3. dim_payment_status
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS gold.dim_payment_status (
    payment_status_key  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payment_status      TEXT    NOT NULL,
    is_unknown          BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT uq_dim_payment_status_natural UNIQUE (payment_status)
);

INSERT INTO gold.dim_payment_status (payment_status_key, payment_status, is_unknown)
VALUES (0, 'Unknown', TRUE)
ON CONFLICT (payment_status_key) DO NOTHING;

INSERT INTO gold.dim_payment_status (payment_status)
SELECT DISTINCT s.payment_status
FROM silver.silver_customer_billing s
WHERE s.payment_status IS NOT NULL
ON CONFLICT (payment_status) DO NOTHING;

-- ---------------------------------------------------------------------------
-- 4. dim_issue_type
--
--    'No Support' is a REAL member (D8): the customer simply did not contact
--    support in that billing cycle. It is not an unknown value.
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS gold.dim_issue_type (
    issue_type_key  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    issue_type      TEXT    NOT NULL,
    is_unknown      BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT uq_dim_issue_type_natural UNIQUE (issue_type)
);

INSERT INTO gold.dim_issue_type (issue_type_key, issue_type, is_unknown)
VALUES (0, 'Unknown', TRUE)
ON CONFLICT (issue_type_key) DO NOTHING;

INSERT INTO gold.dim_issue_type (issue_type)
SELECT DISTINCT s.primary_issue_type
FROM silver.silver_customer_billing s
WHERE s.primary_issue_type IS NOT NULL
ON CONFLICT (issue_type) DO NOTHING;

INSERT INTO gold.dim_issue_type (issue_type)
VALUES ('No Support')
ON CONFLICT (issue_type) DO NOTHING;

-- ---------------------------------------------------------------------------
-- 5. dim_support_channel
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS gold.dim_support_channel (
    support_channel_key  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    support_channel      TEXT    NOT NULL,
    is_unknown           BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT uq_dim_support_channel_natural UNIQUE (support_channel)
);

INSERT INTO gold.dim_support_channel (support_channel_key, support_channel, is_unknown)
VALUES (0, 'Unknown', TRUE)
ON CONFLICT (support_channel_key) DO NOTHING;

INSERT INTO gold.dim_support_channel (support_channel)
SELECT DISTINCT s.support_channel
FROM silver.silver_customer_billing s
WHERE s.support_channel IS NOT NULL
ON CONFLICT (support_channel) DO NOTHING;

INSERT INTO gold.dim_support_channel (support_channel)
VALUES ('None')
ON CONFLICT (support_channel) DO NOTHING;

-- ---------------------------------------------------------------------------
-- 6. fact_billing_support
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS gold.fact_billing_support (
    fact_key                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    -- foreign keys (never NULL: unknown members are used instead)
    customer_key               INTEGER NOT NULL REFERENCES gold.dim_customer(customer_key),
    billing_start_date_key     INTEGER NOT NULL REFERENCES gold.dim_date(date_key),
    billing_end_date_key       INTEGER NOT NULL REFERENCES gold.dim_date(date_key),
    payment_due_date_key       INTEGER NOT NULL REFERENCES gold.dim_date(date_key),
    last_interaction_date_key  INTEGER NOT NULL REFERENCES gold.dim_date(date_key),
    payment_status_key         INTEGER NOT NULL REFERENCES gold.dim_payment_status(payment_status_key),
    issue_type_key             INTEGER NOT NULL REFERENCES gold.dim_issue_type(issue_type_key),
    channel_key                INTEGER NOT NULL REFERENCES gold.dim_support_channel(support_channel_key),

    -- degenerate dimensions
    escalation_flag            BOOLEAN,
    churn_flag                 BOOLEAN,

    -- measures
    call_minutes               BIGINT,
    data_usage_gb              DOUBLE PRECISION,
    sms_count                  BIGINT,
    internet_sessions          BIGINT,
    total_bill_amount          NUMERIC(12,2),
    late_fee                   NUMERIC(12,2),
    discounts_applied          NUMERIC(12,2),
    support_interaction_count  BIGINT,
    resolution_time_minutes    BIGINT,
    satisfaction_score         BIGINT,

    -- Grain enforcement + ON CONFLICT arbiter
    CONSTRAINT uq_fact_grain UNIQUE (customer_key, billing_start_date_key)
);

COMMENT ON TABLE gold.fact_billing_support IS
  'Fact table. Grain: 1 row = 1 billing cycle of 1 customer. Business key (customer_id, billing_cycle_start).';

CREATE INDEX IF NOT EXISTS ix_fact_billing_start ON gold.fact_billing_support (billing_start_date_key);
CREATE INDEX IF NOT EXISTS ix_fact_customer      ON gold.fact_billing_support (customer_key);
CREATE INDEX IF NOT EXISTS ix_fact_payment       ON gold.fact_billing_support (payment_status_key);
CREATE INDEX IF NOT EXISTS ix_fact_issue         ON gold.fact_billing_support (issue_type_key);
CREATE INDEX IF NOT EXISTS ix_fact_channel       ON gold.fact_billing_support (channel_key);

INSERT INTO gold.fact_billing_support (
    customer_key,
    billing_start_date_key,
    billing_end_date_key,
    payment_due_date_key,
    last_interaction_date_key,
    payment_status_key,
    issue_type_key,
    channel_key,
    escalation_flag,
    churn_flag,
    call_minutes,
    data_usage_gb,
    sms_count,
    internet_sessions,
    total_bill_amount,
    late_fee,
    discounts_applied,
    support_interaction_count,
    resolution_time_minutes,
    satisfaction_score
)
SELECT
    COALESCE(c.customer_key, 0),
    COALESCE(ds.date_key, 0),
    COALESCE(de.date_key, 0),
    COALESCE(dp.date_key, 0),
    COALESCE(dl.date_key, 0),
    COALESCE(ps.payment_status_key, 0),
    COALESCE(it.issue_type_key, 0),
    COALESCE(ch.support_channel_key, 0),
    s.escalation_flag,
    s.has_churned,
    s.call_minutes,
    s.data_usage_gb,
    s.sms_count,
    s.internet_sessions,
    s.total_bill_amount,
    s.late_fee,
    s.discounts_applied,
    s.support_interaction_count,
    s.resolution_time_minutes,
    s.satisfaction_score
FROM silver.silver_customer_billing s
LEFT JOIN gold.dim_customer        c  ON c.customer_id      = s.customer_id
LEFT JOIN gold.dim_date            ds ON ds.full_date       = s.billing_cycle_start
LEFT JOIN gold.dim_date            de ON de.full_date       = s.billing_cycle_end
LEFT JOIN gold.dim_date            dp ON dp.full_date       = s.payment_due_date
LEFT JOIN gold.dim_date            dl ON dl.full_date       = s.last_interaction_date
LEFT JOIN gold.dim_payment_status  ps ON ps.payment_status  = s.payment_status
-- D8/D9: a missing issue type / channel means "no support contact", which is a
-- known business state, not an unknown value.
LEFT JOIN gold.dim_issue_type      it ON it.issue_type      = COALESCE(s.primary_issue_type, 'No Support')
LEFT JOIN gold.dim_support_channel ch ON ch.support_channel = COALESCE(s.support_channel, 'None')
ON CONFLICT ON CONSTRAINT uq_fact_grain DO NOTHING;

COMMIT;
